// Regenerates THIRD_PARTY_NOTICES.md from the installed production dependencies
// plus the bundled/vendored assets that npm doesn't know about.
//   node scripts/gen-licenses.mjs
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { cwd: root, encoding: 'utf8' }));
const seen = new Map();
(function walk(deps = {}) {
  for (const [name, info] of Object.entries(deps)) {
    const key = `${name}@${info.version}`;
    if (!seen.has(key)) seen.set(key, name);
    walk(info.dependencies);
  }
})(tree.dependencies);

const licenseFile = (dir) => fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|-|$)/i.test(f));
const out = [
  '# Third-party notices',
  '',
  'Covo is MIT-licensed (see `LICENSE`). It includes or depends on the following third-party software.',
  'Each component keeps its own license, reproduced below. Generated by `scripts/gen-licenses.mjs`.',
  '',
  '## Bundled assets (not installed through npm)',
  '',
  '| Component | Where | License |',
  '|---|---|---|',
  '| Preact 10 + htm (standalone build) | `web/vendor/preact-htm.js` | MIT (Preact) · Apache-2.0 (htm) |',
  '| Lucide icons (path data, some modified) | `web/js/lib/icons.js` | ISC; Feather-derived icons MIT |',
  '| Inter, Source Serif 4, IBM Plex Sans Arabic | `web/fonts/` | SIL Open Font License 1.1 (`web/fonts/LICENSE-OFL.txt`) |',
  '',
  '## npm dependencies (production)',
  '',
  '| Package | Version | License |',
  '|---|---|---|',
];
const texts = [];
for (const [key, name] of [...seen.entries()].sort()) {
  const dir = path.join(root, 'node_modules', name);
  if (!fs.existsSync(path.join(dir, 'package.json'))) continue; // optional peer deps that aren't installed
  let pkg = {};
  try { pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')); } catch {}
  const lic = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type || 'see package';
  out.push(`| ${name} | ${pkg.version || ''} | ${lic} |`);
  const lf = fs.existsSync(dir) && licenseFile(dir);
  if (lf) texts.push(`### ${name} ${pkg.version}\n\n\`\`\`\n${fs.readFileSync(path.join(dir, lf), 'utf8').trim()}\n\`\`\`\n`);
}
// Browser edition + Android app: these dev packages are bundled into dist/web/js/local by esbuild.
const BUNDLED = ['buffer', 'base64-js', 'ieee754', 'events', 'path-browserify', 'fast-sha256'];
out.push('', '## Bundled into the browser edition and the Android app', '', '| Package | Version | License |', '|---|---|---|');
for (const name of BUNDLED) {
  const dir = path.join(root, 'node_modules', name);
  if (!fs.existsSync(path.join(dir, 'package.json'))) continue;
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  out.push(`| ${name} | ${pkg.version} | ${pkg.license} |`);
  const lf = licenseFile(dir);
  if (lf && ![...seen.values()].includes(name)) texts.push(`### ${name} ${pkg.version}\n\n\`\`\`\n${fs.readFileSync(path.join(dir, lf), 'utf8').trim()}\n\`\`\`\n`);
}
// Desktop (Electron) and Android (Capacitor, AndroidX) app shells.
out.push('', '## App shells', '', '| Component | Used in | License |', '|---|---|---|',
  '| Electron (includes Chromium and Node.js) | Desktop app | MIT; Chromium/Node.js licenses ship inside the app as `LICENSES.chromium.html` |',
  '| Capacitor (core, android) | Android app | MIT |',
  '| AndroidX libraries | Android app | Apache-2.0 |');
for (const [label, f] of [['Electron', 'desktop/node_modules/electron/LICENSE'], ['Capacitor', 'mobile/node_modules/@capacitor/core/LICENSE']]) {
  if (fs.existsSync(path.join(root, f))) texts.push(`### ${label}\n\n\`\`\`\n${fs.readFileSync(path.join(root, f), 'utf8').trim()}\n\`\`\`\n`);
}

out.push('', '## License texts', '');
out.push(`### Preact\n\n\`\`\`\n${fs.readFileSync(path.join(root, 'licenses/preact-MIT.txt'), 'utf8').trim()}\n\`\`\`\n`);
out.push(`### Lucide\n\n\`\`\`\n${fs.readFileSync(path.join(root, 'licenses/lucide-ISC.txt'), 'utf8').trim()}\n\`\`\`\n`);
out.push(...texts);
out.push('### Fonts\n\nSee `web/fonts/LICENSE-OFL.txt`.\n');
out.push('### AndroidX\n\nApache License 2.0 — https://www.apache.org/licenses/LICENSE-2.0\n');
fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n') + '\n');
console.log(`THIRD_PARTY_NOTICES.md: ${seen.size} packages`);
